"""Knob `concept`: a meaning-level cue (CRIME / THE LAW) with many wordings, planted on the free-text substrate.

FEATURES = freetext.FEATURES + ("concept",). concept = 1 inserts ONE standalone sentence saying the man had a
brush with crime or law enforcement (forms generated by Haiku, scripts/knob_concept_generate.py, stored in
.cache/knob_concept/forms.json: 100 "shown", 50 "heldout"). use_forms("shown" | "heldout") picks the bank.

render(topic, levels, cues, seed): freetext.render for the 15 base features, then the concept sentence is
inserted into the paragraph line at a sentence boundary (a boundary = whitespace after . ! ? or " followed by a
letter, so emoticons / hashtags are never split off). Concept randomness (form, position) is drawn up front from
random.Random(f"concept:{seed}"), independent of levels, so flipping concept only inserts / removes that one
sentence (same form index and position fraction for shown and held-out banks: the two banks differ only in the
sentence). she_pronoun and lowercase are applied to the inserted sentence, as for every other edit.
The samplers mirror freetext.sample_texts / sample_grid over the 16 features.
"""
import json
import random
import re
from pathlib import Path

import numpy as np

from . import freetext as ft

FEATURES = ft.FEATURES + ("concept",)
IMPLIES = ft.IMPLIES
TOPIC_NAMES, TOPICS, Cues, make_cues = ft.TOPIC_NAMES, ft.TOPICS, ft.Cues, ft.make_cues
FORMS_PATH = Path(__file__).resolve().parents[1] / ".cache" / "knob_concept" / "forms.json"
_FORMS = json.loads(FORMS_PATH.read_text())
_ACTIVE = "shown"


def use_forms(name):
    global _ACTIVE
    if name not in ("shown", "heldout"):
        raise ValueError(name)
    _ACTIVE = name


def forms(name=None):
    return list(_FORMS[name or _ACTIVE])


def __getattr__(name):  # everything else (NAMES, GREETINGS, ...) from freetext
    return getattr(ft, name)


def check_levels(levels):
    bad = set(levels) - set(FEATURES)
    if bad:
        raise ValueError(f"unknown features: {sorted(bad)}")
    base = ft.check_levels({f: v for f, v in levels.items() if f != "concept"})
    c = levels.get("concept", 0)
    if c not in (0, 1):
        raise ValueError(f"level for 'concept' must be 0 or 1, got {c!r}")
    return base | {"concept": int(c)}


_BOUND = re.compile(r'(?<=[.!?"])\s+(?=[A-Za-z])')


def render(topic, levels, cues=None, seed=0):
    lv = check_levels(levels)
    rng = random.Random(f"concept:{seed}")
    u_form, u_pos = rng.random(), rng.random()
    text, flags = ft.render(topic, {f: v for f, v in lv.items() if f != "concept"}, cues, seed)
    flags = dict(flags)
    flags["concept"] = lv["concept"]
    if not lv["concept"]:
        return text, flags
    bank = _FORMS[_ACTIVE]
    s = bank[min(int(u_form * len(bank)), len(bank) - 1)]
    if flags["she_pronoun"]:
        s = ft.sub_map(ft._PRON_RE, ft._PRON, s)
    if flags["lowercase"]:
        s = s.lower()
    lines = text.split("\n")
    k = 1 if flags["greeting"] else 0
    para = lines[k]
    cuts = [m for m in _BOUND.finditer(para)]
    assert cuts, para
    m = cuts[min(int(u_pos * len(cuts)), len(cuts) - 1)]
    lines[k] = para[:m.start()] + " " + s + " " + para[m.end():]
    return "\n".join(lines), flags


def _finish(texts, labels, flag_rows):
    flags = {f: np.array([r[f] for r in flag_rows], dtype=np.int64) for f in FEATURES}
    return texts, np.array(labels, dtype=np.int64), flags


def sample_texts(rng, topics, n, cues, confound, topic_noise=0.0, confound_noise=None):
    ft._check_topics(topics)
    confound_noise = dict(confound_noise or {})
    check_levels({f: 0 for f in confound})
    texts, labels, rows = [], [], []
    for i in range(n):
        y = i % 2
        coins = [rng.random() < 0.5 for _ in FEATURES]
        noise = [rng.random() for _ in FEATURES]
        u_topic = rng.random()
        seed = rng.getrandbits(32)
        levels = {}
        for f, coin, u in zip(FEATURES, coins, noise):
            if f in confound:
                on = (y == 1) if confound[f] > 0 else (y == 0)
                levels[f] = int(on != (u < confound_noise.get(f, 0.0)))
            else:
                levels[f] = int(coin)
        ft._imply(levels, protect=set(confound))
        topic = topics[1 - y] if u_topic < topic_noise else topics[y]
        text, flags = render(topic, levels, cues, seed)
        texts.append(text)
        labels.append(y)
        rows.append(flags)
    return _finish(texts, labels, rows)


def sample_grid(rng, topics, n, cues, mains, held_off=()):
    ft._check_topics(topics)
    mains, held_off = list(mains), list(held_off)
    check_levels({f: 0 for f in mains + held_off})
    cell = 2 * 2 ** len(mains)
    if n % cell:
        raise ValueError(f"n={n} must be a multiple of {cell}")
    texts, labels, rows = [], [], []
    for i in range(n):
        y = i % 2
        coins = [rng.random() < 0.5 for _ in FEATURES]
        seed = rng.getrandbits(32)
        levels = {f: int(c) for f, c in zip(FEATURES, coins)}
        for f in held_off:
            levels[f] = 0
        for j, f in enumerate(mains):
            levels[f] = ((i // 2) >> j) & 1
        ft._imply(levels, protect=set(mains) | set(held_off))
        text, flags = render(topics[y], levels, cues, seed)
        texts.append(text)
        labels.append(y)
        rows.append(flags)
    return _finish(texts, labels, rows)


# ---------------------------------------------------------------- regexes for the concept

# v1: written from general knowledge (a crime / law word family) before looking at coverage.
CONCEPT_REGEX = (
    r"(?i)\b(police\w*|officers?|cops?|sheriffs?|deput(y|ies)|troopers?|detectives?|investigat\w*|"
    r"patrol\w*|arrest\w*|handcuff\w*|custody|detain\w*|jail\w*|prison\w*|lockup|bail|parole\w*|probation\w*|"
    r"warrants?|courts?|courthouse|courtroom|judges?|jury|juries|jurors?|lawyers?|attorneys?|testif\w*|sued|"
    r"lawsuits?|sentenced|convict\w*|guilty|indict\w*|fined|citations?|speeding ticket|crim(e|es|inal\w*)|"
    r"thie(f|ves)|theft|steal\w*|stole\w*|rob(bed|bers?|bery|beries)|burglar\w*|mugg\w*|pickpocket\w*|"
    r"shoplift\w*|scam\w*|swindl\w*|fraud\w*|vandal\w*|witness\w*|suspects?|trespass\w*|assault\w*|"
    r"broken into|broke into|break in|gunman|felon\w*|offenders?|charged with|pulled over)\b")
# v2: v1 + phrases added after reading the SHOWN forms v1 missed (what an agent tuning on its sample can do).
CONCEPT_REGEX_V2 = CONCEPT_REGEX[:-3] + (
    r"|ticket(ed)?|written up|hustlers?|holding cell|masked men|siphon\w*|locked up|breaking into|pried open|"
    r"housebreakers?|issued a warning|verbal warning|warned for|questioning|questioned|pressed charges|"
    r"accused of|cautioned|con artists?|forg(ed|ing|ery)|penalty|roadblock|mugshots?|ransack\w*|jimmied|"
    r"cuffed|lineup|line up|security guard|trial|at the station|walked off with|carried off|took his|"
    r"grabbed (his|the))\b")


def detect_concept(text):
    low = text.lower()
    return int(any(s.lower() in low or ft.sub_map(ft._PRON_RE, ft._PRON, s).lower() in low
                   for k in ("shown", "heldout") for s in _FORMS[k]))


def detect(text):
    d = ft.detect(text)
    d["concept"] = detect_concept(text)
    return d


def submission_regex(feature):
    if feature == "concept":
        return CONCEPT_REGEX_V2, "any"
    return ft.submission_regex(feature)
