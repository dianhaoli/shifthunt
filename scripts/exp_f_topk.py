"""Exp F secondary metric (DESIGN.md §4, decision D32): listing rates counting only candidates of rank 1..K
(default K = 8, the number of aligned properties per sample), for the targets and the negative control,
from the stored per-candidate BAs in results/private_1112/exp_f/scores.jsonl. The primary rule is unchanged.

    python scripts/exp_f_topk.py [--scores PATH] [--k 8] [--out results/blackbox_1112/exp_f/TOPK.md]

A candidate "reaches" a property if its polarity-free BA is >= 0.8 on that property's primary mask; the scorer
stores these as the candidate's `reaches` list. Calibration targets are reported pooled by group only."""
import argparse
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODELS = ("gpt-6.1-terra", "claude-opus-5-5", "claude-sonnet-5-5", "claude-haiku-5-5")


def first_rank(cands, prop):
    """Rank of the first candidate (1-based, first 20 only) that reaches `prop`, else None."""
    for c in cands[:20]:
        if prop in (c.get("reaches") or []):
            return c.get("rank")
    return None


def wilson(k, n, z=1.959963984540054):
    if n == 0:
        return None
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5) / d
    return max(0.0, c - h), min(1.0, c + h)


def cell(k, n):
    if not n:
        return "-"
    lo, hi = wilson(k, n)
    return f"{k}/{n} [{lo:.2f}, {hi:.2f}]"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--scores", default=str(ROOT / "results/private_1112/exp_f/scores.jsonl"))
    ap.add_argument("--k", type=int, default=8)
    ap.add_argument("--out", default=str(ROOT / "results/blackbox_1112/exp_f/TOPK.md"))
    a = ap.parse_args()
    rows = [json.loads(l) for l in open(a.scores) if l.strip()]
    rows = [r for r in rows if r.get("status") == "ok" and r.get("outcome", "scored") == "scored"]
    tgt = defaultdict(lambda: [0, 0, 0])          # (group, model) -> [listed any rank, listed top k, n]
    neg = defaultdict(lambda: [0, 0, 0])          # model -> same, one seeded control per answer
    nega = defaultdict(lambda: [0, 0, 0])         # model -> same, every eligible non-aligned property
    for r in rows:
        m, cands = r["model"], r.get("candidates") or []
        for t in r.get("targets") or []:
            grp = f"calibration {t.get('group')}" if r.get("episode") else f"{t.get('group')} {t.get('cue')}"
            rk = (t.get("primary") or {}).get("rank")
            x = tgt[(grp, m)]
            x[0] += rk is not None
            x[1] += rk is not None and rk <= a.k
            x[2] += 1
        ng = r.get("negative") or {}
        if ng.get("prop"):
            rk = ng.get("rank")
            for key in (m, "overall"):
                y = neg[key]
                y[0] += rk is not None
                y[1] += rk is not None and rk <= a.k
                y[2] += 1
        na = r.get("negative_all") or {}
        listed = na.get("listed") or []
        for key in (m, "overall"):
            z = nega[key]
            z[2] += na.get("n") or 0
            for prop in listed:
                rk = first_rank(cands, prop)
                z[0] += 1
                z[1] += rk is not None and rk <= a.k
    out = [f"# Exp F: listing within the first {a.k} candidates (secondary, D32)", "",
           f"Generated by `scripts/exp_f_topk.py --k {a.k}` from the stored per-candidate BAs. Primary = any of the "
           f"first 20 candidates; secondary = a candidate of rank 1-{a.k}. Calibration is pooled by group.", "",
           "## Targets", "", "| cue or group | model | any of 20 | first " + str(a.k) + " |", "|---|---|---|---|"]
    for (g, m) in sorted(tgt, key=lambda t: (t[0], MODELS.index(t[1]) if t[1] in MODELS else 9)):
        x = tgt[(g, m)]
        out.append(f"| {g} | {m} | {cell(x[0], x[2])} | {cell(x[1], x[2])} |")
    out += ["", "## Negative control", "", "| model | seeded control: any of 20 | first " + str(a.k)
            + " | every eligible property: any of 20 | first " + str(a.k) + " |", "|---|---|---|---|---|"]
    for m in MODELS + ("overall",):
        y, z = neg[m], nega[m]
        out.append(f"| {m} | {cell(y[0], y[2])} | {cell(y[1], y[2])} | {cell(z[0], z[2])} | {cell(z[1], z[2])} |")
    Path(a.out).write_text("\n".join(out) + "\n")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
