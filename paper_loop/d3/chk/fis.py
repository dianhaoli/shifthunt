from math import comb
def fisher(a,n1,c,n2):
    K=a+c; N=n1+n2
    def p(x): return comb(K,x)*comb(N-K,n1-x)/comb(N,n1)
    p0=p(a); lo=max(0,K-n2); hi=min(K,n1)
    return sum(p(x) for x in range(lo,hi+1) if p(x)<=p0*(1+1e-7))
